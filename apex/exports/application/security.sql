-- Native APEX Accounts fournit l'identité de session; PKG_GC_SECURITY résout APP_USER.
-- Exécuter comme propriétaire GC_APP avec deux schémas runtime dédiés déjà créés.
-- Usage SQL*Plus: @security.sql GC_APEX_RUNTIME GC_ORDS_RUNTIME
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE ON

DEFINE APEX_RUNTIME_SCHEMA = &1
DEFINE ORDS_RUNTIME_SCHEMA = &2

DECLARE
  L_APEX_SCHEMA VARCHAR2(128) := UPPER('&&APEX_RUNTIME_SCHEMA');
  L_ORDS_SCHEMA VARCHAR2(128) := UPPER('&&ORDS_RUNTIME_SCHEMA');
  L_SCHEMA_COUNT PLS_INTEGER;
  L_DML_GRANT_COUNT PLS_INTEGER;
BEGIN
  IF L_APEX_SCHEMA = 'GC_APP' OR L_ORDS_SCHEMA = 'GC_APP' OR L_APEX_SCHEMA = L_ORDS_SCHEMA
     OR NOT REGEXP_LIKE(L_APEX_SCHEMA, '^GC_[A-Z0-9_]+$')
     OR NOT REGEXP_LIKE(L_ORDS_SCHEMA, '^GC_[A-Z0-9_]+$') THEN
    RAISE_APPLICATION_ERROR(-20004, 'Runtime schemas must be dedicated GC_* schemas, distinct from GC_APP.');
  END IF;

  SELECT COUNT(*) INTO L_SCHEMA_COUNT
    FROM ALL_USERS
   WHERE USERNAME IN (L_APEX_SCHEMA, L_ORDS_SCHEMA);
  IF L_SCHEMA_COUNT <> 2 THEN
    RAISE_APPLICATION_ERROR(-20004, 'Both dedicated runtime schemas must exist before applying grants.');
  END IF;

  SELECT COUNT(*) INTO L_DML_GRANT_COUNT
    FROM USER_TAB_PRIVS_MADE
   WHERE GRANTEE IN (L_APEX_SCHEMA, L_ORDS_SCHEMA)
     AND PRIVILEGE IN ('INSERT', 'UPDATE', 'DELETE');
  IF L_DML_GRANT_COUNT > 0 THEN
    RAISE_APPLICATION_ERROR(-20004, 'Runtime schemas already have direct DML grants; review and revoke them first.');
  END IF;
END;
/

GRANT SELECT ON GC_APP.VW_GC_CUSTOMER_LIST TO &&APEX_RUNTIME_SCHEMA;
GRANT SELECT ON GC_APP.VW_GC_STOCK_AVAILABILITY TO &&APEX_RUNTIME_SCHEMA;
GRANT EXECUTE ON GC_APP.PKG_GC_ERRORS TO &&APEX_RUNTIME_SCHEMA;
GRANT EXECUTE ON GC_APP.PKG_GC_SECURITY TO &&APEX_RUNTIME_SCHEMA;

GRANT SELECT ON GC_APP.VW_GC_CUSTOMER_LIST TO &&ORDS_RUNTIME_SCHEMA;
GRANT SELECT ON GC_APP.VW_GC_STOCK_AVAILABILITY TO &&ORDS_RUNTIME_SCHEMA;
GRANT EXECUTE ON GC_APP.PKG_GC_ERRORS TO &&ORDS_RUNTIME_SCHEMA;
GRANT EXECUTE ON GC_APP.PKG_GC_SECURITY TO &&ORDS_RUNTIME_SCHEMA;

UNDEFINE APEX_RUNTIME_SCHEMA
UNDEFINE ORDS_RUNTIME_SCHEMA