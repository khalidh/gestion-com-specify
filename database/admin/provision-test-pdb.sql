WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET ECHO OFF
SET VERIFY OFF
SET FEEDBACK ON
SET DEFINE ON

DECLARE
  L_CURRENT_CONTAINER VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CON_NAME');
  L_PDB_COUNT PLS_INTEGER;
  L_USERS_TABLESPACE_COUNT PLS_INTEGER;
  L_EXISTING_USERS PLS_INTEGER;
BEGIN
  IF L_CURRENT_CONTAINER <> 'CDB$ROOT' THEN
    RAISE_APPLICATION_ERROR(-20004, 'Connect locally as SYSDBA to CDB$ROOT.');
  END IF;

  SELECT COUNT(*) INTO L_PDB_COUNT FROM V$PDBS WHERE NAME = 'GC_TEST_PDB' AND OPEN_MODE = 'READ WRITE';
  IF L_PDB_COUNT <> 1 THEN
    RAISE_APPLICATION_ERROR(-20004, 'GC_TEST_PDB must exist and be open READ WRITE.');
  END IF;
END;
/

ALTER SESSION SET CONTAINER = GC_TEST_PDB;

DECLARE
  L_USERS_TABLESPACE_COUNT PLS_INTEGER;
  L_EXISTING_USERS PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO L_USERS_TABLESPACE_COUNT
    FROM DBA_TABLESPACES WHERE TABLESPACE_NAME = 'USERS';
  IF L_USERS_TABLESPACE_COUNT > 0 THEN
    RAISE_APPLICATION_ERROR(-20004, 'USERS tablespace already exists; refusing to replace it.');
  END IF;

  SELECT COUNT(*) INTO L_EXISTING_USERS
    FROM DBA_USERS
   WHERE USERNAME IN ('GC_APP', 'GC_TEST_APEX_RUNTIME', 'GC_TEST_ORDS_RUNTIME');
  IF L_EXISTING_USERS > 0 THEN
    RAISE_APPLICATION_ERROR(-20004, 'A target schema already exists; refusing to reset credentials or grants.');
  END IF;
END;
/

PROMPT Create unique passwords of at least 20 characters using letters, digits, _ or # only.
PROMPT Passwords are hidden and are not written to this script.
ACCEPT GC_APP_PASSWORD CHAR PROMPT 'GC_APP password (hidden): ' HIDE
ACCEPT APEX_RUNTIME_PASSWORD CHAR PROMPT 'GC_TEST_APEX_RUNTIME password (hidden): ' HIDE
ACCEPT ORDS_RUNTIME_PASSWORD CHAR PROMPT 'GC_TEST_ORDS_RUNTIME password (hidden): ' HIDE

CREATE TABLESPACE USERS
  DATAFILE 'C:\APP\ADMINISTRATOR\ORADATA\ORCL\GC_TEST_PDB\USERS01.DBF'
  SIZE 128M AUTOEXTEND ON NEXT 64M MAXSIZE 1024M;

CREATE USER GC_APP IDENTIFIED BY "&&GC_APP_PASSWORD"
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP
  QUOTA 768M ON USERS;

GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE PROCEDURE, CREATE TRIGGER, CREATE SEQUENCE TO GC_APP;

CREATE USER GC_TEST_APEX_RUNTIME IDENTIFIED BY "&&APEX_RUNTIME_PASSWORD"
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP;
GRANT CREATE SESSION TO GC_TEST_APEX_RUNTIME;

CREATE USER GC_TEST_ORDS_RUNTIME IDENTIFIED BY "&&ORDS_RUNTIME_PASSWORD"
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP;
GRANT CREATE SESSION TO GC_TEST_ORDS_RUNTIME;

UNDEFINE GC_APP_PASSWORD
UNDEFINE APEX_RUNTIME_PASSWORD
UNDEFINE ORDS_RUNTIME_PASSWORD

PROMPT GC_TEST_PDB is provisioned with empty GC_APP and locked-down runtime schemas.
EXIT SUCCESS