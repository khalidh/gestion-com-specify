WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET ECHO OFF
SET VERIFY OFF
SET FEEDBACK ON
SET DEFINE ON

DECLARE
  L_CURRENT_CONTAINER VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CON_NAME');
  L_PDB_COUNT PLS_INTEGER;
BEGIN
  IF L_CURRENT_CONTAINER <> 'CDB$ROOT' THEN
    RAISE_APPLICATION_ERROR(-20004, 'Connect as SYSDBA to CDB$ROOT before creating the test PDB.');
  END IF;

  SELECT COUNT(*)
    INTO L_PDB_COUNT
    FROM V$PDBS
   WHERE NAME = 'GC_TEST_PDB';

  IF L_PDB_COUNT > 0 THEN
    RAISE_APPLICATION_ERROR(-20004, 'GC_TEST_PDB already exists; refusing to overwrite it.');
  END IF;
END;
/

PROMPT Enter a new 20+ character password for PDBADMIN.
PROMPT Use mixed-case letters, digits, and _ or #; do not use quotes, ampersands, or spaces.
ACCEPT PDB_ADMIN_PASSWORD CHAR PROMPT 'PDBADMIN password (hidden): ' HIDE

CREATE PLUGGABLE DATABASE GC_TEST_PDB
  ADMIN USER PDBADMIN IDENTIFIED BY "&&PDB_ADMIN_PASSWORD"
  ROLES = (DBA)
  FILE_NAME_CONVERT = (
    'C:\APP\ADMINISTRATOR\ORADATA\ORCL\PDBSEED\',
    'C:\APP\ADMINISTRATOR\ORADATA\ORCL\GC_TEST_PDB\'
  );

UNDEFINE PDB_ADMIN_PASSWORD

ALTER PLUGGABLE DATABASE GC_TEST_PDB OPEN READ WRITE;
ALTER PLUGGABLE DATABASE GC_TEST_PDB SAVE STATE;

PROMPT GC_TEST_PDB created and opened READ WRITE.
EXIT SUCCESS