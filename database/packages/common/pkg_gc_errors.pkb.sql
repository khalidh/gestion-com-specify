CREATE OR REPLACE PACKAGE BODY GC_APP.PKG_GC_ERRORS AS
  FUNCTION NEW_CORRELATION_ID RETURN VARCHAR2 IS
  BEGIN
    RETURN LOWER(RAWTOHEX(SYS_GUID()));
  END NEW_CORRELATION_ID;

  PROCEDURE RAISE_ERROR (
    P_ERROR_CODE IN PLS_INTEGER,
    P_MESSAGE IN VARCHAR2,
    P_CORRELATION_ID IN VARCHAR2 DEFAULT NULL
  ) IS
    L_CORRELATION_ID VARCHAR2(32767) := COALESCE(P_CORRELATION_ID, NEW_CORRELATION_ID());
    L_MESSAGE VARCHAR2(2048);
    L_MESSAGE_TEXT VARCHAR2(400);
  BEGIN
    IF P_ERROR_CODE IS NULL OR P_ERROR_CODE NOT BETWEEN -20999 AND -20000 THEN
      RAISE_APPLICATION_ERROR(
        C_INVALID_ERROR_CODE,
        'GC-20000: Code erreur applicatif hors plage.'
      );
    END IF;

     IF LENGTH(L_CORRELATION_ID) > 64
       OR NOT REGEXP_LIKE(L_CORRELATION_ID, '^[[:alnum:]_.:-]{1,64}$') THEN
      RAISE_APPLICATION_ERROR(
        C_INVALID_ERROR_CODE,
        'GC-20000: Identifiant de corrélation invalide.'
      );
    END IF;

    L_MESSAGE_TEXT := SUBSTR(COALESCE(TRIM(P_MESSAGE), 'Erreur applicative.'), 1, 400);
    L_MESSAGE := 'GC' || TO_CHAR(P_ERROR_CODE) || ': ' || L_MESSAGE_TEXT
      || ' [correlation_id=' || L_CORRELATION_ID || ']';

    RAISE_APPLICATION_ERROR(P_ERROR_CODE, L_MESSAGE);
  END RAISE_ERROR;
END PKG_GC_ERRORS;
