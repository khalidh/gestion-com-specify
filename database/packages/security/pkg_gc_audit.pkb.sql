CREATE OR REPLACE PACKAGE BODY GC_APP.PKG_GC_AUDIT AS
  PROCEDURE INSERT_EVENT (
    P_ACTION_CODE IN VARCHAR2,
    P_OBJECT_TYPE IN VARCHAR2,
    P_OBJECT_REFERENCE IN VARCHAR2,
    P_EVENT_RESULT IN VARCHAR2,
    P_REASON IN VARCHAR2,
    P_CORRELATION_ID IN VARCHAR2
  ) IS
    L_ACTION_CODE VARCHAR2(32767) := UPPER(TRIM(P_ACTION_CODE));
    L_OBJECT_TYPE VARCHAR2(32767) := UPPER(TRIM(P_OBJECT_TYPE));
    L_EVENT_RESULT VARCHAR2(32767) := UPPER(TRIM(P_EVENT_RESULT));
    L_CORRELATION_ID VARCHAR2(32767) := COALESCE(P_CORRELATION_ID, GC_APP.PKG_GC_ERRORS.NEW_CORRELATION_ID());
    L_ACTOR_USER_ID NUMBER := GC_APP.PKG_GC_SECURITY.CURRENT_USER_ID();
  BEGIN
     IF L_ACTION_CODE IS NULL OR LENGTH(L_ACTION_CODE) > 64
       OR NOT REGEXP_LIKE(L_ACTION_CODE, '^[A-Z][A-Z0-9_]*$')
       OR L_OBJECT_TYPE IS NULL OR LENGTH(L_OBJECT_TYPE) > 64
       OR NOT REGEXP_LIKE(L_OBJECT_TYPE, '^[A-Z][A-Z0-9_]*$')
      OR L_EVENT_RESULT IS NULL OR L_EVENT_RESULT NOT IN ('SUCCESS', 'DENIED', 'FAILURE')
       OR LENGTH(L_CORRELATION_ID) > 64
       OR NOT REGEXP_LIKE(L_CORRELATION_ID, '^[[:alnum:]_.:-]{1,64}$') THEN
      GC_APP.PKG_GC_ERRORS.RAISE_ERROR(
        P_ERROR_CODE => GC_APP.PKG_GC_ERRORS.C_VALIDATION_ERROR,
        P_MESSAGE => 'Événement d’audit invalide.'
      );
    END IF;

    INSERT INTO GC_APP.GC_AUDIT_EVENT (
      ACTOR_USER_ID,
      ACTION_CODE,
      OBJECT_TYPE,
      OBJECT_REFERENCE,
      EVENT_RESULT,
      REASON,
      CORRELATION_ID
    ) VALUES (
      L_ACTOR_USER_ID,
      L_ACTION_CODE,
      L_OBJECT_TYPE,
      SUBSTR(P_OBJECT_REFERENCE, 1, 256),
      L_EVENT_RESULT,
      SUBSTR(TRIM(P_REASON), 1, 1000),
      L_CORRELATION_ID
    );
  END INSERT_EVENT;

  PROCEDURE WRITE_EVENT (
    P_ACTION_CODE IN VARCHAR2,
    P_OBJECT_TYPE IN VARCHAR2,
    P_OBJECT_REFERENCE IN VARCHAR2,
    P_EVENT_RESULT IN VARCHAR2,
    P_REASON IN VARCHAR2 DEFAULT NULL,
    P_CORRELATION_ID IN VARCHAR2 DEFAULT NULL
  ) IS
  BEGIN
    INSERT_EVENT(
      P_ACTION_CODE,
      P_OBJECT_TYPE,
      P_OBJECT_REFERENCE,
      P_EVENT_RESULT,
      P_REASON,
      P_CORRELATION_ID
    );
  END WRITE_EVENT;

  PROCEDURE WRITE_SECURITY_EVENT (
    P_ACTION_CODE IN VARCHAR2,
    P_OBJECT_TYPE IN VARCHAR2,
    P_OBJECT_REFERENCE IN VARCHAR2,
    P_REASON IN VARCHAR2,
    P_CORRELATION_ID IN VARCHAR2 DEFAULT NULL
  ) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
  BEGIN
    INSERT_EVENT(
      P_ACTION_CODE,
      P_OBJECT_TYPE,
      P_OBJECT_REFERENCE,
      'DENIED',
      P_REASON,
      P_CORRELATION_ID
    );
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      ROLLBACK;
      RAISE;
  END WRITE_SECURITY_EVENT;
END PKG_GC_AUDIT;
