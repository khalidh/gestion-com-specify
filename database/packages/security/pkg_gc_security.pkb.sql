CREATE OR REPLACE PACKAGE BODY GC_APP.PKG_GC_SECURITY AS
  FUNCTION CURRENT_USER_ID RETURN NUMBER IS
    L_APP_USER VARCHAR2(4000) := SYS_CONTEXT('APEX$SESSION', 'APP_USER');
    L_USER_ID NUMBER;
  BEGIN
    IF L_APP_USER IS NULL
       OR UPPER(TRIM(L_APP_USER)) IN ('NOBODY', 'APEX_PUBLIC_USER')
       OR LENGTH(TRIM(L_APP_USER)) > 128 THEN
      RETURN NULL;
    END IF;

    SELECT USER_ID
      INTO L_USER_ID
      FROM GC_APP.GC_USER_ACCOUNT
     WHERE NORMALIZED_LOGIN = UPPER(TRIM(L_APP_USER))
       AND STATUS = 'ACTIVE'
       AND LOCKED_AT IS NULL;

    RETURN L_USER_ID;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RETURN NULL;
  END CURRENT_USER_ID;

  FUNCTION HAS_PERMISSION (
    P_PERMISSION_CODE IN VARCHAR2
  ) RETURN BOOLEAN IS
    L_USER_ID NUMBER;
    L_PERMISSION_CODE VARCHAR2(64);
    L_MATCH_COUNT PLS_INTEGER;
  BEGIN
    IF P_PERMISSION_CODE IS NULL OR LENGTH(TRIM(P_PERMISSION_CODE)) > 64 THEN
      RETURN FALSE;
    END IF;

    L_PERMISSION_CODE := UPPER(TRIM(P_PERMISSION_CODE));
    IF NOT REGEXP_LIKE(L_PERMISSION_CODE, '^[A-Z][A-Z0-9_]*$') THEN
      RETURN FALSE;
    END IF;

    L_USER_ID := CURRENT_USER_ID();
    IF L_USER_ID IS NULL THEN
      RETURN FALSE;
    END IF;

    SELECT COUNT(*)
      INTO L_MATCH_COUNT
      FROM GC_APP.GC_USER_ROLE USER_ROLE
      JOIN GC_APP.GC_ROLE ROLE_DEF
        ON ROLE_DEF.ROLE_ID = USER_ROLE.ROLE_ID
      JOIN GC_APP.GC_ROLE_PERMISSION ROLE_PERMISSION
        ON ROLE_PERMISSION.ROLE_ID = ROLE_DEF.ROLE_ID
      JOIN GC_APP.GC_PERMISSION PERMISSION_DEF
        ON PERMISSION_DEF.PERMISSION_ID = ROLE_PERMISSION.PERMISSION_ID
     WHERE USER_ROLE.USER_ID = L_USER_ID
       AND USER_ROLE.EFFECTIVE_FROM <= SYSTIMESTAMP
       AND (USER_ROLE.EFFECTIVE_TO IS NULL OR USER_ROLE.EFFECTIVE_TO > SYSTIMESTAMP)
       AND ROLE_DEF.STATUS = 'ACTIVE'
       AND PERMISSION_DEF.STATUS = 'ACTIVE'
       AND PERMISSION_DEF.PERMISSION_CODE = L_PERMISSION_CODE;

    RETURN L_MATCH_COUNT > 0;
  END HAS_PERMISSION;

  PROCEDURE REQUIRE_PERMISSION (
    P_PERMISSION_CODE IN VARCHAR2
  ) IS
    L_PERMISSION_CODE VARCHAR2(32767) := UPPER(TRIM(P_PERMISSION_CODE));
    L_CORRELATION_ID VARCHAR2(64) := GC_APP.PKG_GC_ERRORS.NEW_CORRELATION_ID();
  BEGIN
    IF HAS_PERMISSION(P_PERMISSION_CODE) THEN
      RETURN;
    END IF;

    GC_APP.PKG_GC_AUDIT.WRITE_SECURITY_EVENT(
      P_ACTION_CODE => 'AUTHORIZATION_DENIED',
      P_OBJECT_TYPE => 'PERMISSION',
      P_OBJECT_REFERENCE => SUBSTR(COALESCE(L_PERMISSION_CODE, 'UNKNOWN'), 1, 64),
      P_REASON => 'Identité absente ou permission non accordée.',
      P_CORRELATION_ID => L_CORRELATION_ID
    );

    GC_APP.PKG_GC_ERRORS.RAISE_ERROR(
      P_ERROR_CODE => GC_APP.PKG_GC_ERRORS.C_FORBIDDEN_ERROR,
      P_MESSAGE => 'Accès refusé.',
      P_CORRELATION_ID => L_CORRELATION_ID
    );
  END REQUIRE_PERMISSION;
END PKG_GC_SECURITY;
