--changeset gestion:inventory-warehouse
CREATE TABLE GC_APP.GC_WAREHOUSE (
  WAREHOUSE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  WAREHOUSE_CODE VARCHAR2(30) NOT NULL,
  LABEL VARCHAR2(120) NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_GC_WAREHOUSE PRIMARY KEY (WAREHOUSE_ID),
  CONSTRAINT UK_GC_WAREHOUSE_CODE UNIQUE (WAREHOUSE_CODE),
  CONSTRAINT CK_GC_WAREHOUSE_CODE CHECK (TRIM(WAREHOUSE_CODE) IS NOT NULL AND WAREHOUSE_CODE = UPPER(TRIM(WAREHOUSE_CODE))),
  CONSTRAINT CK_GC_WAREHOUSE_LABEL CHECK (TRIM(LABEL) IS NOT NULL),
  CONSTRAINT CK_GC_WAREHOUSE_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

--changeset gestion:inventory-stock-balance
CREATE TABLE GC_APP.GC_STOCK_BALANCE (
  PRODUCT_ID NUMBER NOT NULL,
  WAREHOUSE_ID NUMBER NOT NULL,
  PHYSICAL_QUANTITY NUMBER(15,3) DEFAULT 0 NOT NULL,
  RESERVED_QUANTITY NUMBER(15,3) DEFAULT 0 NOT NULL,
  SAFETY_STOCK_QUANTITY NUMBER(15,3) DEFAULT 0 NOT NULL,
  VERSION_NO NUMBER(12) DEFAULT 1 NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_GC_STOCK_BALANCE PRIMARY KEY (PRODUCT_ID, WAREHOUSE_ID),
  CONSTRAINT FK_GC_STOCK_BALANCE_WAREHOUSE FOREIGN KEY (WAREHOUSE_ID) REFERENCES GC_APP.GC_WAREHOUSE (WAREHOUSE_ID),
  CONSTRAINT CK_GC_STOCK_BALANCE_PRODUCT CHECK (PRODUCT_ID > 0),
  CONSTRAINT CK_GC_STOCK_BALANCE_QUANTITIES CHECK (
    PHYSICAL_QUANTITY >= 0
    AND RESERVED_QUANTITY >= 0
    AND RESERVED_QUANTITY <= PHYSICAL_QUANTITY
    AND SAFETY_STOCK_QUANTITY >= 0
  ),
  CONSTRAINT CK_GC_STOCK_BALANCE_VERSION CHECK (VERSION_NO > 0)
);

--changeset gestion:inventory-stock-movement
CREATE TABLE GC_APP.GC_STOCK_MOVEMENT (
  MOVEMENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  PRODUCT_ID NUMBER NOT NULL,
  WAREHOUSE_ID NUMBER NOT NULL,
  MOVEMENT_TYPE VARCHAR2(30) NOT NULL,
  DIRECTION VARCHAR2(3) NOT NULL,
  QUANTITY NUMBER(15,3) NOT NULL,
  SOURCE_TYPE VARCHAR2(40) NOT NULL,
  SOURCE_REFERENCE VARCHAR2(128) NOT NULL,
  MOVED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  ACTOR_USER_ID NUMBER NOT NULL,
  REASON VARCHAR2(1000) NOT NULL,
  CORRELATION_ID VARCHAR2(64) NOT NULL,
  CONSTRAINT PK_GC_STOCK_MOVEMENT PRIMARY KEY (MOVEMENT_ID),
  CONSTRAINT FK_GC_STOCK_MOVEMENT_WAREHOUSE FOREIGN KEY (WAREHOUSE_ID) REFERENCES GC_APP.GC_WAREHOUSE (WAREHOUSE_ID),
  CONSTRAINT FK_GC_STOCK_MOVEMENT_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES GC_APP.GC_USER_ACCOUNT (USER_ID),
  CONSTRAINT CK_GC_STOCK_MOVEMENT_PRODUCT CHECK (PRODUCT_ID > 0),
  CONSTRAINT CK_GC_STOCK_MOVEMENT_TYPE CHECK (TRIM(MOVEMENT_TYPE) IS NOT NULL),
  CONSTRAINT CK_GC_STOCK_MOVEMENT_SOURCE CHECK (TRIM(SOURCE_TYPE) IS NOT NULL AND TRIM(SOURCE_REFERENCE) IS NOT NULL),
  CONSTRAINT CK_GC_STOCK_MOVEMENT_DIRECTION CHECK (DIRECTION IN ('IN', 'OUT')),
  CONSTRAINT CK_GC_STOCK_MOVEMENT_QUANTITY CHECK (QUANTITY > 0),
  CONSTRAINT CK_GC_STOCK_MOVEMENT_REASON CHECK (LENGTH(TRIM(REASON)) > 0),
  CONSTRAINT CK_GC_STOCK_MOVEMENT_CORRELATION CHECK (LENGTH(TRIM(CORRELATION_ID)) BETWEEN 1 AND 64)
);

CREATE INDEX GC_APP.IX_GC_STOCK_MOVEMENT_PRODUCT_DATE ON GC_APP.GC_STOCK_MOVEMENT (PRODUCT_ID, WAREHOUSE_ID, MOVED_AT);
CREATE INDEX GC_APP.IX_GC_STOCK_MOVEMENT_SOURCE ON GC_APP.GC_STOCK_MOVEMENT (SOURCE_TYPE, SOURCE_REFERENCE);

--changeset gestion:inventory-stock-reservation
CREATE TABLE GC_APP.GC_STOCK_RESERVATION (
  RESERVATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  PRODUCT_ID NUMBER NOT NULL,
  WAREHOUSE_ID NUMBER NOT NULL,
  SOURCE_TYPE VARCHAR2(40) NOT NULL,
  SOURCE_REFERENCE VARCHAR2(128) NOT NULL,
  QUANTITY NUMBER(15,3) NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY_USER_ID NUMBER NOT NULL,
  CLOSED_AT TIMESTAMP WITH TIME ZONE,
  CONSTRAINT PK_GC_STOCK_RESERVATION PRIMARY KEY (RESERVATION_ID),
  CONSTRAINT FK_GC_STOCK_RESERVATION_WAREHOUSE FOREIGN KEY (WAREHOUSE_ID) REFERENCES GC_APP.GC_WAREHOUSE (WAREHOUSE_ID),
  CONSTRAINT FK_GC_STOCK_RESERVATION_ACTOR FOREIGN KEY (CREATED_BY_USER_ID) REFERENCES GC_APP.GC_USER_ACCOUNT (USER_ID),
  CONSTRAINT CK_GC_STOCK_RESERVATION_PRODUCT CHECK (PRODUCT_ID > 0),
  CONSTRAINT CK_GC_STOCK_RESERVATION_SOURCE CHECK (TRIM(SOURCE_TYPE) IS NOT NULL AND TRIM(SOURCE_REFERENCE) IS NOT NULL),
  CONSTRAINT CK_GC_STOCK_RESERVATION_QUANTITY CHECK (QUANTITY > 0),
  CONSTRAINT CK_GC_STOCK_RESERVATION_STATUS CHECK (STATUS IN ('ACTIVE', 'RELEASED', 'CONSUMED', 'CANCELLED')),
  CONSTRAINT CK_GC_STOCK_RESERVATION_CLOSED CHECK (STATUS = 'ACTIVE' OR CLOSED_AT IS NOT NULL)
);

CREATE INDEX GC_APP.IX_GC_STOCK_RESERVATION_PRODUCT ON GC_APP.GC_STOCK_RESERVATION (PRODUCT_ID, WAREHOUSE_ID, STATUS);
CREATE INDEX GC_APP.IX_GC_STOCK_RESERVATION_SOURCE ON GC_APP.GC_STOCK_RESERVATION (SOURCE_TYPE, SOURCE_REFERENCE);

--changeset gestion:inventory-stock-availability-view
CREATE OR REPLACE VIEW GC_APP.VW_GC_STOCK_AVAILABILITY AS
SELECT PRODUCT_ID,
       WAREHOUSE_ID,
       PHYSICAL_QUANTITY,
       RESERVED_QUANTITY,
       SAFETY_STOCK_QUANTITY,
       PHYSICAL_QUANTITY - RESERVED_QUANTITY - SAFETY_STOCK_QUANTITY AS AVAILABLE_QUANTITY,
       VERSION_NO
  FROM GC_APP.GC_STOCK_BALANCE;