CREATE OR REPLACE PACKAGE BODY GC_APP.PKG_GC_CUSTOMER AS
  PROCEDURE SEARCH_CUSTOMER (
    P_SEARCH IN VARCHAR2,
    P_PARTY_ID OUT NUMBER,
    P_PARTY_CODE OUT VARCHAR2,
    P_LEGAL_NAME OUT VARCHAR2,
    P_VAT_ID OUT VARCHAR2,
    P_ADDRESS_LINE_1 OUT VARCHAR2,
    P_POSTAL_CODE OUT VARCHAR2,
    P_CITY OUT VARCHAR2,
    P_CREDIT_LIMIT_EUR OUT NUMBER,
    P_EMAIL OUT VARCHAR2,
    P_PHONE OUT VARCHAR2
  ) IS
    L_SEARCH VARCHAR2(240) := UPPER(TRIM(P_SEARCH));
  BEGIN
    IF L_SEARCH IS NULL THEN
      RAISE_APPLICATION_ERROR(-20010, 'Saisir un code ou un nom de client.');
    END IF;

    SELECT P.PARTY_ID,
           P.PARTY_CODE,
           P.LEGAL_NAME,
           P.VAT_ID,
           A.ADDRESS_LINE_1,
           A.POSTAL_CODE,
           A.CITY,
           CUST.CREDIT_LIMIT_EUR,
           CONTACT.EMAIL,
           CONTACT.PHONE
      INTO P_PARTY_ID,
           P_PARTY_CODE,
           P_LEGAL_NAME,
           P_VAT_ID,
           P_ADDRESS_LINE_1,
           P_POSTAL_CODE,
           P_CITY,
           P_CREDIT_LIMIT_EUR,
           P_EMAIL,
           P_PHONE
      FROM GC_APP.GC_PARTY P
      JOIN GC_APP.GC_CUSTOMER CUST ON CUST.PARTY_ID = P.PARTY_ID
      LEFT JOIN (
        SELECT PARTY_ID, ADDRESS_LINE_1, POSTAL_CODE, CITY,
               ROW_NUMBER() OVER (PARTITION BY PARTY_ID ORDER BY EFFECTIVE_FROM DESC, ADDRESS_ID DESC) AS RN
          FROM GC_APP.GC_PARTY_ADDRESS
         WHERE ADDRESS_TYPE = 'BILLING'
           AND EFFECTIVE_FROM <= TRUNC(SYSDATE)
           AND (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= TRUNC(SYSDATE))
      ) A ON A.PARTY_ID = P.PARTY_ID AND A.RN = 1
      LEFT JOIN (
        SELECT PARTY_ID, EMAIL, PHONE,
               ROW_NUMBER() OVER (PARTITION BY PARTY_ID ORDER BY CONTACT_ID) AS RN
          FROM GC_APP.GC_PARTY_CONTACT
         WHERE STATUS = 'ACTIVE'
      ) CONTACT ON CONTACT.PARTY_ID = P.PARTY_ID AND CONTACT.RN = 1
     WHERE UPPER(P.PARTY_CODE) = L_SEARCH
        OR UPPER(P.LEGAL_NAME) LIKE '%' || L_SEARCH || '%'
        OR UPPER(NVL(P.DISPLAY_NAME, P.LEGAL_NAME)) LIKE '%' || L_SEARCH || '%'
     ORDER BY CASE WHEN UPPER(P.PARTY_CODE) = L_SEARCH THEN 0 ELSE 1 END,
              P.PARTY_ID
     FETCH FIRST 1 ROW ONLY;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20011, 'Aucun client correspondant.');
  END SEARCH_CUSTOMER;

  PROCEDURE CREATE_CUSTOMER (
    P_PARTY_CODE IN VARCHAR2,
    P_LEGAL_NAME IN VARCHAR2,
    P_ADDRESS_LINE_1 IN VARCHAR2,
    P_POSTAL_CODE IN VARCHAR2,
    P_CITY IN VARCHAR2,
    P_PARTY_ID OUT NUMBER,
    P_VAT_ID IN VARCHAR2 DEFAULT NULL,
    P_CREDIT_LIMIT_EUR IN NUMBER DEFAULT 0,
    P_EMAIL IN VARCHAR2 DEFAULT NULL,
    P_PHONE IN VARCHAR2 DEFAULT NULL
  ) IS
  BEGIN
    SAVEPOINT GC_CUSTOMER_CREATE;
    GC_APP.PKG_GC_PARTY.CREATE_CUSTOMER(
      P_PARTY_CODE => P_PARTY_CODE,
      P_LEGAL_NAME => P_LEGAL_NAME,
      P_DISPLAY_NAME => P_LEGAL_NAME,
      P_VAT_ID => P_VAT_ID,
      P_ADDRESS_LINE_1 => P_ADDRESS_LINE_1,
      P_POSTAL_CODE => P_POSTAL_CODE,
      P_CITY => P_CITY,
      P_CREDIT_LIMIT_EUR => P_CREDIT_LIMIT_EUR,
      P_EMAIL => P_EMAIL,
      P_PHONE => P_PHONE,
      P_PARTY_ID => P_PARTY_ID
    );
  EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
      ROLLBACK TO GC_CUSTOMER_CREATE;
      RAISE_APPLICATION_ERROR(-20015, 'Ce code client existe déjà.');
    WHEN OTHERS THEN
      ROLLBACK TO GC_CUSTOMER_CREATE;
      RAISE;
  END CREATE_CUSTOMER;

  PROCEDURE UPDATE_CUSTOMER (
    P_PARTY_ID IN NUMBER,
    P_PARTY_CODE IN VARCHAR2,
    P_LEGAL_NAME IN VARCHAR2,
    P_VAT_ID IN VARCHAR2,
    P_ADDRESS_LINE_1 IN VARCHAR2,
    P_POSTAL_CODE IN VARCHAR2,
    P_CITY IN VARCHAR2,
    P_CREDIT_LIMIT_EUR IN NUMBER,
    P_EMAIL IN VARCHAR2,
    P_PHONE IN VARCHAR2
  ) IS
    L_ADDRESS_ID NUMBER;
    L_CONTACT_ID NUMBER;
  BEGIN
    SAVEPOINT GC_CUSTOMER_UPDATE;
    IF P_PARTY_ID IS NULL
       OR TRIM(P_PARTY_CODE) IS NULL
       OR TRIM(P_LEGAL_NAME) IS NULL
       OR TRIM(P_ADDRESS_LINE_1) IS NULL
       OR TRIM(P_POSTAL_CODE) IS NULL
       OR TRIM(P_CITY) IS NULL THEN
      RAISE_APPLICATION_ERROR(-20012, 'Code, raison sociale et adresse complète sont obligatoires.');
    END IF;
    IF P_CREDIT_LIMIT_EUR IS NULL OR P_CREDIT_LIMIT_EUR < 0 THEN
      RAISE_APPLICATION_ERROR(-20013, 'Le plafond de crédit doit être positif ou nul.');
    END IF;

    UPDATE GC_APP.GC_PARTY
       SET PARTY_CODE = UPPER(TRIM(P_PARTY_CODE)),
           LEGAL_NAME = TRIM(P_LEGAL_NAME),
           DISPLAY_NAME = TRIM(P_LEGAL_NAME),
           VAT_ID = NULLIF(TRIM(P_VAT_ID), ''),
           UPDATED_AT = SYSTIMESTAMP,
           UPDATED_BY = SYS_CONTEXT('USERENV', 'SESSION_USER')
     WHERE PARTY_ID = P_PARTY_ID;
    IF SQL%ROWCOUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20014, 'Client introuvable.');
    END IF;

    UPDATE GC_APP.GC_CUSTOMER
       SET CREDIT_LIMIT_EUR = P_CREDIT_LIMIT_EUR
     WHERE PARTY_ID = P_PARTY_ID;
    IF SQL%ROWCOUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20014, 'Client introuvable.');
    END IF;

    BEGIN
      SELECT ADDRESS_ID INTO L_ADDRESS_ID
        FROM (
          SELECT ADDRESS_ID
            FROM GC_APP.GC_PARTY_ADDRESS
           WHERE PARTY_ID = P_PARTY_ID
             AND ADDRESS_TYPE = 'BILLING'
             AND EFFECTIVE_FROM <= TRUNC(SYSDATE)
             AND (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= TRUNC(SYSDATE))
           ORDER BY EFFECTIVE_FROM DESC, ADDRESS_ID DESC
        )
       WHERE ROWNUM = 1;
      UPDATE GC_APP.GC_PARTY_ADDRESS
         SET ADDRESS_LINE_1 = TRIM(P_ADDRESS_LINE_1),
             POSTAL_CODE = TRIM(P_POSTAL_CODE),
             CITY = TRIM(P_CITY)
       WHERE ADDRESS_ID = L_ADDRESS_ID;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        INSERT INTO GC_APP.GC_PARTY_ADDRESS (
          PARTY_ID, ADDRESS_TYPE, ADDRESS_LINE_1, POSTAL_CODE, CITY, COUNTRY_CODE
        ) VALUES (
          P_PARTY_ID, 'BILLING', TRIM(P_ADDRESS_LINE_1), TRIM(P_POSTAL_CODE), TRIM(P_CITY), 'FR'
        );
    END;

    BEGIN
      SELECT CONTACT_ID INTO L_CONTACT_ID
        FROM (
          SELECT CONTACT_ID
            FROM GC_APP.GC_PARTY_CONTACT
           WHERE PARTY_ID = P_PARTY_ID AND STATUS = 'ACTIVE'
           ORDER BY CONTACT_ID
        )
       WHERE ROWNUM = 1;
      UPDATE GC_APP.GC_PARTY_CONTACT
         SET EMAIL = NULLIF(TRIM(P_EMAIL), ''),
             PHONE = NULLIF(TRIM(P_PHONE), '')
       WHERE CONTACT_ID = L_CONTACT_ID;
    EXCEPTION
      WHEN NO_DATA_FOUND THEN
        IF TRIM(P_EMAIL) IS NOT NULL OR TRIM(P_PHONE) IS NOT NULL THEN
          INSERT INTO GC_APP.GC_PARTY_CONTACT (PARTY_ID, CONTACT_NAME, EMAIL, PHONE)
          VALUES (P_PARTY_ID, TRIM(P_LEGAL_NAME), NULLIF(TRIM(P_EMAIL), ''), NULLIF(TRIM(P_PHONE), ''));
        END IF;
    END;
  EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
      ROLLBACK TO GC_CUSTOMER_UPDATE;
      RAISE_APPLICATION_ERROR(-20015, 'Ce code client existe déjà.');
    WHEN OTHERS THEN
      ROLLBACK TO GC_CUSTOMER_UPDATE;
      RAISE;
  END UPDATE_CUSTOMER;

  PROCEDURE DELETE_CUSTOMER (P_PARTY_ID IN NUMBER) IS
    L_CUSTOMER_COUNT PLS_INTEGER;
  BEGIN
    SAVEPOINT GC_CUSTOMER_DELETE;
    IF P_PARTY_ID IS NULL THEN
      RAISE_APPLICATION_ERROR(-20016, 'Sélectionner un client avant suppression.');
    END IF;
    SELECT COUNT(*) INTO L_CUSTOMER_COUNT
      FROM GC_APP.GC_CUSTOMER
     WHERE PARTY_ID = P_PARTY_ID;
    IF L_CUSTOMER_COUNT <> 1 THEN
      RAISE_APPLICATION_ERROR(-20014, 'Client introuvable.');
    END IF;
    DELETE FROM GC_APP.GC_PARTY_CONTACT WHERE PARTY_ID = P_PARTY_ID;
    DELETE FROM GC_APP.GC_PARTY_ADDRESS WHERE PARTY_ID = P_PARTY_ID;
    DELETE FROM GC_APP.GC_CUSTOMER WHERE PARTY_ID = P_PARTY_ID;
    DELETE FROM GC_APP.GC_PARTY WHERE PARTY_ID = P_PARTY_ID;
  EXCEPTION
    WHEN OTHERS THEN
      ROLLBACK TO GC_CUSTOMER_DELETE;
      RAISE;
  END DELETE_CUSTOMER;
END PKG_GC_CUSTOMER;
