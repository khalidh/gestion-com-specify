--changeset gestion:security-user-role
CREATE TABLE GC_APP.GC_USER_ROLE (
  USER_ID NUMBER NOT NULL,
  ROLE_ID NUMBER NOT NULL,
  EFFECTIVE_FROM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  EFFECTIVE_TO TIMESTAMP,
  ASSIGNED_BY_USER_ID NUMBER NOT NULL,
  REVOKED_BY_USER_ID NUMBER,
  REVOCATION_REASON VARCHAR2(1000),
  CONSTRAINT PK_GC_USER_ROLE PRIMARY KEY (USER_ID, ROLE_ID, EFFECTIVE_FROM),
  CONSTRAINT FK_GC_USER_ROLE_USER FOREIGN KEY (USER_ID) REFERENCES GC_APP.GC_USER_ACCOUNT (USER_ID),
  CONSTRAINT FK_GC_USER_ROLE_ROLE FOREIGN KEY (ROLE_ID) REFERENCES GC_APP.GC_ROLE (ROLE_ID),
  CONSTRAINT FK_GC_USER_ROLE_ASSIGNED_BY FOREIGN KEY (ASSIGNED_BY_USER_ID) REFERENCES GC_APP.GC_USER_ACCOUNT (USER_ID),
  CONSTRAINT FK_GC_USER_ROLE_REVOKED_BY FOREIGN KEY (REVOKED_BY_USER_ID) REFERENCES GC_APP.GC_USER_ACCOUNT (USER_ID),
  CONSTRAINT CK_GC_USER_ROLE_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM),
  CONSTRAINT CK_GC_USER_ROLE_REVOCATION CHECK (
    (REVOKED_BY_USER_ID IS NULL AND REVOCATION_REASON IS NULL)
    OR (REVOKED_BY_USER_ID IS NOT NULL AND EFFECTIVE_TO IS NOT NULL AND TRIM(REVOCATION_REASON) IS NOT NULL)
  )
);

CREATE INDEX GC_APP.IX_GC_USER_ROLE_ACTIVE ON GC_APP.GC_USER_ROLE (USER_ID, EFFECTIVE_TO, EFFECTIVE_FROM);

