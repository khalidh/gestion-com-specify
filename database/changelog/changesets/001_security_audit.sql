CREATE TABLE GC_APP.GC_USER_MFA_FACTOR (
  FACTOR_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  USER_ID NUMBER NOT NULL,
  FACTOR_TYPE VARCHAR2(30) NOT NULL,
    ENCRYPTED_SECRET_REFERENCE VARCHAR2(512),
  PROVIDER_REFERENCE VARCHAR2(512),
  STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
  ENROLLED_AT TIMESTAMP WITH TIME ZONE,
  REVOKED_AT TIMESTAMP WITH TIME ZONE,
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_GC_USER_MFA_FACTOR PRIMARY KEY (FACTOR_ID),
  CONSTRAINT FK_GC_USER_MFA_FACTOR_USER FOREIGN KEY (USER_ID) REFERENCES GC_APP.GC_USER_ACCOUNT (USER_ID),
  CONSTRAINT CK_GC_USER_MFA_FACTOR_MATERIAL CHECK (
      (ENCRYPTED_SECRET_REFERENCE IS NOT NULL AND PROVIDER_REFERENCE IS NULL)
      OR (ENCRYPTED_SECRET_REFERENCE IS NULL AND PROVIDER_REFERENCE IS NOT NULL)
  ),
  CONSTRAINT CK_GC_USER_MFA_FACTOR_STATUS CHECK (STATUS IN ('PENDING', 'ACTIVE', 'REVOKED')),
  CONSTRAINT CK_GC_USER_MFA_FACTOR_TYPE CHECK (TRIM(FACTOR_TYPE) IS NOT NULL),
  CONSTRAINT CK_GC_USER_MFA_FACTOR_DATES CHECK (
    (STATUS <> 'ACTIVE' OR ENROLLED_AT IS NOT NULL)
    AND (STATUS <> 'REVOKED' OR REVOKED_AT IS NOT NULL)
  )
);

CREATE INDEX GC_APP.IX_GC_USER_MFA_FACTOR_USER ON GC_APP.GC_USER_MFA_FACTOR (USER_ID, STATUS);

