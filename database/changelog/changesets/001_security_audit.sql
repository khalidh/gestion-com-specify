CREATE TABLE GC_APP.GC_USER_ACCOUNT (
  USER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NORMALIZED_LOGIN VARCHAR2(128) NOT NULL,
  DISPLAY_NAME VARCHAR2(240) NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  LAST_ACCESS_AT TIMESTAMP WITH TIME ZONE,
  LOCKED_AT TIMESTAMP WITH TIME ZONE,
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE,
  CONSTRAINT PK_GC_USER_ACCOUNT PRIMARY KEY (USER_ID),
  CONSTRAINT UK_GC_USER_ACCOUNT_LOGIN UNIQUE (NORMALIZED_LOGIN),
  CONSTRAINT CK_GC_USER_ACCOUNT_LOGIN CHECK (TRIM(NORMALIZED_LOGIN) IS NOT NULL AND NORMALIZED_LOGIN = UPPER(TRIM(NORMALIZED_LOGIN))),
  CONSTRAINT CK_GC_USER_ACCOUNT_NAME CHECK (TRIM(DISPLAY_NAME) IS NOT NULL),
  CONSTRAINT CK_GC_USER_ACCOUNT_STATUS CHECK (STATUS IN ('ACTIVE', 'LOCKED', 'DISABLED'))
);

