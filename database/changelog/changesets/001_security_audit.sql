CREATE TABLE GC_APP.GC_AUDIT_EVENT (
  AUDIT_EVENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ACTOR_USER_ID NUMBER,
  EVENT_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  ACTION_CODE VARCHAR2(64) NOT NULL,
  OBJECT_TYPE VARCHAR2(64) NOT NULL,
  OBJECT_REFERENCE VARCHAR2(256),
  EVENT_RESULT VARCHAR2(16) NOT NULL,
  REASON VARCHAR2(1000),
  CORRELATION_ID VARCHAR2(64) NOT NULL,
  CONSTRAINT PK_GC_AUDIT_EVENT PRIMARY KEY (AUDIT_EVENT_ID),
  CONSTRAINT FK_GC_AUDIT_EVENT_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES GC_APP.GC_USER_ACCOUNT (USER_ID),
  CONSTRAINT CK_GC_AUDIT_EVENT_RESULT CHECK (EVENT_RESULT IN ('SUCCESS', 'DENIED', 'FAILURE')),
  CONSTRAINT CK_GC_AUDIT_EVENT_CORRELATION CHECK (LENGTH(TRIM(CORRELATION_ID)) BETWEEN 1 AND 64)
);

CREATE INDEX GC_APP.IX_GC_AUDIT_EVENT_ACTOR_DATE ON GC_APP.GC_AUDIT_EVENT (ACTOR_USER_ID, EVENT_AT);
CREATE INDEX GC_APP.IX_GC_AUDIT_EVENT_OBJECT_DATE ON GC_APP.GC_AUDIT_EVENT (OBJECT_TYPE, OBJECT_REFERENCE, EVENT_AT);

