CREATE OR REPLACE PACKAGE BODY GC_APP.PKG_GC_PARTY AS
  PROCEDURE CREATE_CUSTOMER (
    P_PARTY_CODE IN VARCHAR2,
    P_LEGAL_NAME IN VARCHAR2,
    P_ADDRESS_LINE_1 IN VARCHAR2,
    P_POSTAL_CODE IN VARCHAR2,
    P_CITY IN VARCHAR2,
    P_PARTY_ID OUT NUMBER,
    P_DISPLAY_NAME IN VARCHAR2 DEFAULT NULL,
    P_VAT_ID IN VARCHAR2 DEFAULT NULL,
    P_CREDIT_LIMIT_EUR IN NUMBER DEFAULT 0,
    P_EMAIL IN VARCHAR2 DEFAULT NULL,
    P_PHONE IN VARCHAR2 DEFAULT NULL,
    P_ADDRESS_LINE_2 IN VARCHAR2 DEFAULT NULL,
    P_COUNTRY_CODE IN VARCHAR2 DEFAULT 'FR'
  ) IS
    L_PARTY_CODE VARCHAR2(30) := UPPER(TRIM(P_PARTY_CODE));
    L_LEGAL_NAME VARCHAR2(240) := TRIM(P_LEGAL_NAME);
    L_ADDRESS_LINE_1 VARCHAR2(240) := TRIM(P_ADDRESS_LINE_1);
    L_POSTAL_CODE VARCHAR2(20) := TRIM(P_POSTAL_CODE);
    L_CITY VARCHAR2(120) := TRIM(P_CITY);
  BEGIN
    IF L_PARTY_CODE IS NULL OR L_LEGAL_NAME IS NULL OR L_ADDRESS_LINE_1 IS NULL
       OR L_POSTAL_CODE IS NULL OR L_CITY IS NULL THEN
      RAISE_APPLICATION_ERROR(-20001, 'Code, raison sociale et adresse de facturation obligatoires.');
    END IF;

    IF P_CREDIT_LIMIT_EUR < 0 THEN
      RAISE_APPLICATION_ERROR(-20002, 'Le plafond de crédit ne peut pas être négatif.');
    END IF;

    INSERT INTO GC_PARTY (PARTY_CODE, LEGAL_NAME, DISPLAY_NAME, VAT_ID)
    VALUES (L_PARTY_CODE, L_LEGAL_NAME, NULLIF(TRIM(P_DISPLAY_NAME), ''), NULLIF(TRIM(P_VAT_ID), ''))
    RETURNING PARTY_ID INTO P_PARTY_ID;

    INSERT INTO GC_CUSTOMER (PARTY_ID, CREDIT_LIMIT_EUR)
    VALUES (P_PARTY_ID, COALESCE(P_CREDIT_LIMIT_EUR, 0));

    INSERT INTO GC_PARTY_ADDRESS (
      PARTY_ID, ADDRESS_TYPE, ADDRESS_LINE_1, ADDRESS_LINE_2,
      POSTAL_CODE, CITY, COUNTRY_CODE
    ) VALUES (
      P_PARTY_ID, 'BILLING', L_ADDRESS_LINE_1, NULLIF(TRIM(P_ADDRESS_LINE_2), ''),
      L_POSTAL_CODE, L_CITY, COALESCE(UPPER(TRIM(P_COUNTRY_CODE)), 'FR')
    );

    IF P_EMAIL IS NOT NULL OR P_PHONE IS NOT NULL THEN
      INSERT INTO GC_PARTY_CONTACT (PARTY_ID, CONTACT_NAME, EMAIL, PHONE)
      VALUES (P_PARTY_ID, COALESCE(NULLIF(TRIM(P_DISPLAY_NAME), ''), L_LEGAL_NAME),
              NULLIF(TRIM(P_EMAIL), ''), NULLIF(TRIM(P_PHONE), ''));
    END IF;
  EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
      RAISE_APPLICATION_ERROR(-20003, 'Ce code client existe deja.');
  END CREATE_CUSTOMER;
END PKG_GC_PARTY;
