CREATE OR REPLACE VIEW GC_APP.VW_GC_CUSTOMER_LIST AS
WITH CURRENT_BILLING_ADDRESS AS (
  SELECT PARTY_ID, POSTAL_CODE, CITY,
         ROW_NUMBER() OVER (PARTITION BY PARTY_ID ORDER BY EFFECTIVE_FROM DESC, ADDRESS_ID DESC) AS RN
    FROM GC_APP.GC_PARTY_ADDRESS
   WHERE ADDRESS_TYPE = 'BILLING'
     AND EFFECTIVE_FROM <= TRUNC(SYSDATE)
     AND (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= TRUNC(SYSDATE))
), FIRST_ACTIVE_CONTACT AS (
  SELECT PARTY_ID, EMAIL, PHONE,
         ROW_NUMBER() OVER (PARTITION BY PARTY_ID ORDER BY CONTACT_ID) AS RN
    FROM GC_APP.GC_PARTY_CONTACT
   WHERE STATUS = 'ACTIVE'
)
SELECT P.PARTY_ID,
       P.PARTY_CODE,
       COALESCE(P.DISPLAY_NAME, P.LEGAL_NAME) AS CUSTOMER_NAME,
       P.LEGAL_NAME,
       C.EMAIL,
       C.PHONE,
       A.POSTAL_CODE,
       A.CITY,
       GC.CREDIT_LIMIT_EUR,
       GC.CREDIT_STATUS,
       P.STATUS,
       P.CREATED_AT
  FROM GC_APP.GC_CUSTOMER GC
  JOIN GC_APP.GC_PARTY P ON P.PARTY_ID = GC.PARTY_ID
  LEFT JOIN CURRENT_BILLING_ADDRESS A ON A.PARTY_ID = P.PARTY_ID AND A.RN = 1
  LEFT JOIN FIRST_ACTIVE_CONTACT C ON C.PARTY_ID = P.PARTY_ID AND C.RN = 1;

