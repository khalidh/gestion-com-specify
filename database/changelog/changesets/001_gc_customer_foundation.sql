CREATE TABLE GC_APP.GC_PARTY (
  PARTY_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  PARTY_CODE VARCHAR2(30) NOT NULL,
  LEGAL_NAME VARCHAR2(240) NOT NULL,
  DISPLAY_NAME VARCHAR2(240),
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  VAT_ID VARCHAR2(32),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE,
  UPDATED_BY VARCHAR2(128),
  CONSTRAINT PK_GC_PARTY PRIMARY KEY (PARTY_ID),
  CONSTRAINT UK_GC_PARTY_CODE UNIQUE (PARTY_CODE),
  CONSTRAINT CK_GC_PARTY_CODE CHECK (PARTY_CODE = UPPER(TRIM(PARTY_CODE))),
  CONSTRAINT CK_GC_PARTY_NAME CHECK (LENGTH(TRIM(LEGAL_NAME)) > 0),
  CONSTRAINT CK_GC_PARTY_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

