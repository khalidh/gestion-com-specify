CREATE TABLE GC_APP.GC_PARTY_ADDRESS (
  ADDRESS_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  PARTY_ID NUMBER NOT NULL,
  ADDRESS_TYPE VARCHAR2(20) NOT NULL,
  ADDRESS_LINE_1 VARCHAR2(240) NOT NULL,
  ADDRESS_LINE_2 VARCHAR2(240),
  POSTAL_CODE VARCHAR2(20) NOT NULL,
  CITY VARCHAR2(120) NOT NULL,
  COUNTRY_CODE CHAR(2) DEFAULT 'FR' NOT NULL,
  EFFECTIVE_FROM DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
  EFFECTIVE_TO DATE,
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
  CONSTRAINT PK_GC_PARTY_ADDRESS PRIMARY KEY (ADDRESS_ID),
  CONSTRAINT FK_GC_PARTY_ADDRESS_PARTY FOREIGN KEY (PARTY_ID) REFERENCES GC_APP.GC_PARTY (PARTY_ID),
  CONSTRAINT CK_GC_PARTY_ADDRESS_TYPE CHECK (ADDRESS_TYPE IN ('BILLING', 'DELIVERY', 'OTHER')),
  CONSTRAINT CK_GC_PARTY_ADDRESS_COUNTRY CHECK (COUNTRY_CODE = UPPER(COUNTRY_CODE)),
  CONSTRAINT CK_GC_PARTY_ADDRESS_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM)
);

CREATE INDEX GC_APP.IX_GC_PARTY_ADDRESS_PARTY ON GC_APP.GC_PARTY_ADDRESS (PARTY_ID, ADDRESS_TYPE, EFFECTIVE_FROM);

