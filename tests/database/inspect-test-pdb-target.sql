WHENEVER SQLERROR EXIT SQL.SQLCODE
SET PAGESIZE 100
SET LINESIZE 220
SET FEEDBACK ON
SET VERIFY OFF

PROMPT === Local Oracle identity ===
SELECT SYS_CONTEXT('USERENV', 'SESSION_USER') AS SESSION_USER,
       SYS_CONTEXT('USERENV', 'CON_NAME') AS CONTAINER_NAME,
       SYS_CONTEXT('USERENV', 'ISDBA') AS IS_DBA
  FROM DUAL;

PROMPT === Datafile placement parameters ===
SELECT NAME, VALUE
  FROM V$PARAMETER
 WHERE NAME IN ('db_create_file_dest', 'db_file_name_convert', 'pdb_file_name_convert')
 ORDER BY NAME;

PROMPT === Existing pluggable databases ===
SELECT PDB_NAME, STATUS
  FROM CDB_PDBS
 ORDER BY PDB_NAME;

PROMPT === PDB seed datafile paths ===
SELECT NAME
  FROM V$DATAFILE
 WHERE CON_ID = 2
 ORDER BY NAME;

PROMPT === GC_TEST_PDB tablespaces ===
ALTER SESSION SET CONTAINER = GC_TEST_PDB;
SELECT TABLESPACE_NAME, STATUS, CONTENTS
  FROM DBA_TABLESPACES
 ORDER BY TABLESPACE_NAME;

PROMPT === GC_TEST_PDB service names ===
SELECT NAME, NETWORK_NAME
  FROM V$SERVICES
 WHERE CON_ID = TO_NUMBER(SYS_CONTEXT('USERENV', 'CON_ID'))
 ORDER BY NAME;

EXIT SUCCESS