WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE ON
SET ECHO OFF
SET VERIFY OFF

DEFINE GC_TEST_PDB_NAME = &1
DEFINE GC_TEST_APEX_RUNTIME_SCHEMA = &2
DEFINE GC_TEST_ORDS_RUNTIME_SCHEMA = &3
DEFINE GC_TEST_TNS_ALIAS = &4

ACCEPT GC_APP_PASSWORD CHAR PROMPT 'GC_APP password (hidden): ' HIDE
CONNECT GC_APP/"&&GC_APP_PASSWORD"@&&GC_TEST_TNS_ALIAS
UNDEFINE GC_APP_PASSWORD

DECLARE
  L_CURRENT_PDB VARCHAR2(128) := UPPER(SYS_CONTEXT('USERENV', 'CON_NAME'));
  L_APEX_SCHEMA VARCHAR2(128) := UPPER('&&GC_TEST_APEX_RUNTIME_SCHEMA');
  L_ORDS_SCHEMA VARCHAR2(128) := UPPER('&&GC_TEST_ORDS_RUNTIME_SCHEMA');
  L_SCHEMA_COUNT PLS_INTEGER;
  L_EXISTING_OBJECTS PLS_INTEGER;
BEGIN
  IF USER <> 'GC_APP' THEN
    RAISE_APPLICATION_ERROR(-20004, 'Connect as GC_APP in the isolated test PDB.');
  END IF;

  IF L_CURRENT_PDB <> UPPER('&&GC_TEST_PDB_NAME')
     OR NOT REGEXP_LIKE(L_CURRENT_PDB, '^GC_TEST_[A-Z0-9_]+$') THEN
    RAISE_APPLICATION_ERROR(-20004, 'Connected PDB does not match the declared isolated GC_TEST_* target.');
  END IF;

  IF L_APEX_SCHEMA = 'GC_APP' OR L_ORDS_SCHEMA = 'GC_APP' OR L_APEX_SCHEMA = L_ORDS_SCHEMA THEN
    RAISE_APPLICATION_ERROR(-20004, 'Runtime schemas must be distinct from GC_APP and from each other.');
  END IF;

  SELECT COUNT(*) INTO L_SCHEMA_COUNT
    FROM ALL_USERS
   WHERE USERNAME IN (L_APEX_SCHEMA, L_ORDS_SCHEMA);
  IF L_SCHEMA_COUNT <> 2 THEN
    RAISE_APPLICATION_ERROR(-20004, 'Dedicated runtime schemas must exist before validation.');
  END IF;

  SELECT COUNT(*) INTO L_EXISTING_OBJECTS FROM USER_OBJECTS;
  IF L_EXISTING_OBJECTS > 0 THEN
    RAISE_APPLICATION_ERROR(-20004, 'GC_APP must contain no database objects; refusing to replay changesets against an existing schema.');
  END IF;
END;
/

PROMPT Isolated PDB preflight passed; no schema changes were applied by this script.
EXIT SUCCESS