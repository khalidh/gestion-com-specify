MERGE INTO GC_APP.GC_USER_ACCOUNT TARGET
USING (
  SELECT 'UT_ADMIN' NORMALIZED_LOGIN, 'Synthetic test administrator' DISPLAY_NAME FROM DUAL
  UNION ALL SELECT 'UT_APPROVER', 'Synthetic test approver' FROM DUAL
  UNION ALL SELECT 'UT_READER', 'Synthetic test reader' FROM DUAL
  UNION ALL SELECT 'UT_AUDITOR', 'Synthetic test auditor' FROM DUAL
) SOURCE
ON (TARGET.NORMALIZED_LOGIN = SOURCE.NORMALIZED_LOGIN)
WHEN MATCHED THEN UPDATE SET
  TARGET.DISPLAY_NAME = SOURCE.DISPLAY_NAME,
  TARGET.STATUS = 'ACTIVE',
  TARGET.LOCKED_AT = NULL
WHEN NOT MATCHED THEN INSERT (NORMALIZED_LOGIN, DISPLAY_NAME, STATUS)
  VALUES (SOURCE.NORMALIZED_LOGIN, SOURCE.DISPLAY_NAME, 'ACTIVE');

MERGE INTO GC_APP.GC_ROLE TARGET
USING (
  SELECT 'UT_ADMIN' ROLE_CODE, 'Synthetic test administrator' LABEL FROM DUAL
  UNION ALL SELECT 'UT_APPROVER', 'Synthetic test approver' FROM DUAL
  UNION ALL SELECT 'UT_READER', 'Synthetic test reader' FROM DUAL
  UNION ALL SELECT 'UT_AUDITOR', 'Synthetic test auditor' FROM DUAL
) SOURCE
ON (TARGET.ROLE_CODE = SOURCE.ROLE_CODE)
WHEN MATCHED THEN UPDATE SET TARGET.LABEL = SOURCE.LABEL, TARGET.STATUS = 'ACTIVE'
WHEN NOT MATCHED THEN INSERT (ROLE_CODE, LABEL, STATUS)
  VALUES (SOURCE.ROLE_CODE, SOURCE.LABEL, 'ACTIVE');

MERGE INTO GC_APP.GC_PERMISSION TARGET
USING (
  SELECT 'USER_ADMIN' PERMISSION_CODE, 'Administer synthetic test users and roles' DESCRIPTION FROM DUAL
  UNION ALL SELECT 'AUDIT_READ', 'Read audit events in isolated tests' FROM DUAL
  UNION ALL SELECT 'STOCK_READ', 'Read stock in isolated tests' FROM DUAL
  UNION ALL SELECT 'STOCK_ADJUST', 'Adjust synthetic stock in isolated tests' FROM DUAL
  UNION ALL SELECT 'ORDER_APPROVE', 'Approve synthetic orders in isolated tests' FROM DUAL
  UNION ALL SELECT 'INVOICE_APPROVE', 'Approve synthetic invoices in isolated tests' FROM DUAL
) SOURCE
ON (TARGET.PERMISSION_CODE = SOURCE.PERMISSION_CODE)
WHEN MATCHED THEN UPDATE SET TARGET.DESCRIPTION = SOURCE.DESCRIPTION, TARGET.STATUS = 'ACTIVE'
WHEN NOT MATCHED THEN INSERT (PERMISSION_CODE, DESCRIPTION, STATUS)
  VALUES (SOURCE.PERMISSION_CODE, SOURCE.DESCRIPTION, 'ACTIVE');

MERGE INTO GC_APP.GC_ROLE_PERMISSION TARGET
USING (
  SELECT ROLE_DEF.ROLE_ID, PERMISSION_DEF.PERMISSION_ID, ADMIN_USER.USER_ID GRANTED_BY_USER_ID
    FROM GC_APP.GC_ROLE ROLE_DEF
    JOIN GC_APP.GC_PERMISSION PERMISSION_DEF
      ON (ROLE_DEF.ROLE_CODE = 'UT_ADMIN' AND PERMISSION_DEF.PERMISSION_CODE IN (
            'USER_ADMIN', 'AUDIT_READ', 'STOCK_READ', 'STOCK_ADJUST', 'ORDER_APPROVE', 'INVOICE_APPROVE'
          ))
      OR (ROLE_DEF.ROLE_CODE = 'UT_APPROVER' AND PERMISSION_DEF.PERMISSION_CODE IN ('ORDER_APPROVE', 'INVOICE_APPROVE'))
      OR (ROLE_DEF.ROLE_CODE = 'UT_READER' AND PERMISSION_DEF.PERMISSION_CODE = 'STOCK_READ')
      OR (ROLE_DEF.ROLE_CODE = 'UT_AUDITOR' AND PERMISSION_DEF.PERMISSION_CODE = 'AUDIT_READ')
    CROSS JOIN GC_APP.GC_USER_ACCOUNT ADMIN_USER
   WHERE ADMIN_USER.NORMALIZED_LOGIN = 'UT_ADMIN'
) SOURCE
ON (TARGET.ROLE_ID = SOURCE.ROLE_ID AND TARGET.PERMISSION_ID = SOURCE.PERMISSION_ID)
WHEN NOT MATCHED THEN INSERT (ROLE_ID, PERMISSION_ID, GRANTED_BY_USER_ID)
  VALUES (SOURCE.ROLE_ID, SOURCE.PERMISSION_ID, SOURCE.GRANTED_BY_USER_ID);

MERGE INTO GC_APP.GC_USER_ROLE TARGET
USING (
  SELECT USER_ACCOUNT.USER_ID, ROLE_DEF.ROLE_ID, ADMIN_USER.USER_ID ASSIGNED_BY_USER_ID
    FROM GC_APP.GC_USER_ACCOUNT USER_ACCOUNT
    JOIN GC_APP.GC_ROLE ROLE_DEF ON ROLE_DEF.ROLE_CODE = USER_ACCOUNT.NORMALIZED_LOGIN
    JOIN GC_APP.GC_USER_ACCOUNT ADMIN_USER ON ADMIN_USER.NORMALIZED_LOGIN = 'UT_ADMIN'
   WHERE USER_ACCOUNT.NORMALIZED_LOGIN IN ('UT_ADMIN', 'UT_APPROVER', 'UT_READER', 'UT_AUDITOR')
) SOURCE
ON (TARGET.USER_ID = SOURCE.USER_ID AND TARGET.ROLE_ID = SOURCE.ROLE_ID AND TARGET.EFFECTIVE_TO IS NULL)
WHEN NOT MATCHED THEN INSERT (USER_ID, ROLE_ID, EFFECTIVE_FROM, ASSIGNED_BY_USER_ID)
  VALUES (SOURCE.USER_ID, SOURCE.ROLE_ID, SYSTIMESTAMP, SOURCE.ASSIGNED_BY_USER_ID);